import { test } from '@playwright/test';
const dir = process.env.SHOT_DIR ?? 'test-results/shots';
test.skip(!process.env.SHOT_DIR, 'yalnızca ekran görüntüsü için');
test('ekran görüntüleri', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('./');
  await page.evaluate(async () => {
    const dbs = await indexedDB.databases?.();
    await Promise.all((dbs ?? []).map((d) => d.name && new Promise((r) => { const q = indexedDB.deleteDatabase(d.name!); q.onsuccess = q.onerror = q.onblocked = () => r(null); })));
  });
  await page.reload();
  await page.getByRole('button', { name: 'Atla' }).click();
  await page.goto('./#/texts');
  await page.getByRole('button', { name: 'Örnek metinleri ekle' }).click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}/m-library.png` });
  await page.goto('./#/');
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${dir}/m-home.png` });
  await page.goto('./#/texts');
  await page.getByRole('button', { name: /^Örnek — 30 saniyelik Reels \d/ }).click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}/m-editor.png` });
  await page.getByLabel('Konuşma 2').click();
  await page.screenshot({ path: `${dir}/m-editor-focus.png` });
  await page.getByRole('button', { name: 'Prompteri aç' }).click();
  await page.locator('.reader').waitFor();
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}/m-reader.png` });
  await page.goto('./#/import');
  await page.getByRole('button', { name: /Örnek metin/ }).click();
  await page.screenshot({ path: `${dir}/m-import.png`, fullPage: true });
  await page.goto('./#/settings');
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}/m-settings.png`, fullPage: true });
  await page.goto('./#/reading-view');
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${dir}/m-reading-view.png` });
});
